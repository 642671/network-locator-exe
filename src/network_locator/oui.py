def normalize_mac(value: str) -> str | None:
    compact = re.sub(r"[-:\s]", "", str(value or "")).upper()
    if not re.fullmatch(r"[0-9A-F]{12}", compact):
        return None
    return "-".join(compact[index : index + 2] for index in range(0, 12, 2))


def describe_mac(value: str) -> tuple[str, bool]:
    """Return ``(vendor, is_locally_administered)`` for a MAC or prefix."""

    compact = re.sub(r"[-:\s]", "", str(value or "")).upper()
    if len(compact) < 6 or not re.fullmatch(r"[0-9A-F]+", compact):
        return "未知厂商", False
    prefix = compact[:6]
    try:
        first_octet = int(compact[:2], 16)
    except ValueError:
        first_octet = 0
    is_local = bool(first_octet & 0x02)
    if is_local:
        return "本地管理地址（随机/虚拟）", True
    return OUI_VENDORS.get(prefix, "未知厂商"), False
